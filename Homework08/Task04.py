# დავალება #8 — ამოცანა 4: Person და __del__
# __del__ არის დესტრუქტორი — გამოიძახება მაშინ, როცა ობიექტზე
# ბოლო მიმართვაც (reference) ქრება და garbage collector მას შლის.
# მნიშვნელოვანი დეტალი: del x არ ნიშნავს "წაშალე ობიექტი".
# del x შლის მხოლოდ სახელს x. ობიექტი მაშინ იშლება, როცა მასზე
# აღარცერთი მიმართვა აღარ რჩება (reference counting).

class Person:
    def __init__(self, name):
        self.name = name
        print(f"Person created: {self.name}")

    def __del__(self):
        print("Person removed")


if __name__ == "__main__":
    print("--- 1. მარტივი შემთხვევა ---")
    p = Person("ნინო")
    del p                      # ბოლო მიმართვა ქრება -> __del__ გამოიძახება
    print("del-ის შემდეგ\n")

    print("--- 2. ორი მიმართვა ერთსა და იმავე ობიექტზე ---")
    a = Person("გიორგი")
    b = a                      # ახლა ორი სახელი ერთ ობიექტზე მიუთითებს
    del a                      # __del__ ჯერ არ გამოიძახება — b ისევ არსებობს
    print("del a შესრულდა, მაგრამ ობიექტი ისევ ცოცხალია (b მიუთითებს მასზე)")
    del b                      # ახლა კი — ბოლო მიმართვაც წაიშალა
    print("del b შესრულდა\n")

    print("--- 3. ავტომატური წაშლა ფუნქციის დასრულებისას ---")

    def make_person():
        temp = Person("დროებითი")
        print("ფუნქცია მთავრდება...")
        # temp ლოკალურია — ფუნქციის დასრულებისას ავტომატურად იშლება

    make_person()
    print("ფუნქციიდან გამოვედით")